"""Modern Facts Shorts generator built on MoneyPrinterTurbo's own CLI.

Pipeline for one YouTube Short:

1. ``ensure_config`` writes ``config.toml`` (fresh CI checkout) and points the
   existing LLM layer at Gemini using ``GEMINI_API_KEY`` from the environment.
2. A topic is either supplied (``--topic`` / ``SHORTS_TOPIC``) or generated by
   Gemini through the repository's existing LLM adapter.
3. Abstract 9:16 background clips are generated locally with FFmpeg
   (``scripts/generate_shorts_backgrounds``), so no stock-footage API key is
   needed. They are fed to the stock pipeline through ``--video-source local``.
4. ``cli.py`` runs the unchanged MoneyPrinterTurbo pipeline: Gemini script →
   Edge TTS voiceover (free, no key) → Edge subtitles → local materials →
   vertical 9:16 MP4 with burned-in captions.
5. The finished MP4, SRT, script, and metadata are copied to an output
   directory for the GitHub Actions artifact upload.
6. When the ``UPLOAD_POST_API_KEY`` and ``UPLOAD_POST_USERNAME`` environment
   variables are present, the *existing* ``app/services/upload_post.py``
   cross-post service publishes the finished video to YouTube (private by
   default) through Upload-Post, whose dashboard is where the YouTube
   OAuth 2.0 consent happens. The upload runs only after video generation
   succeeds, its outcome is written to ``upload-status.json``, and an upload
   failure never changes the generation exit code or the artifact.

Usage:
    export GEMINI_API_KEY=...
    uv run python scripts/run_modern_facts_shorts.py
    uv run python scripts/run_modern_facts_shorts.py --topic "..." --script "..."
    uv run python scripts/run_modern_facts_shorts.py --verify-upload-status storage/modern_facts/upload-status.json
"""

