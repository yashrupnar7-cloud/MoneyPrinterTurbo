def resolve_materials(args: argparse.Namespace, log) -> list[Path]:
    explicit = [part.strip() for part in (args.materials or "").split(",") if part.strip()]
    if explicit:
        paths = [Path(item).expanduser().resolve() for item in explicit]
        missing = [str(path) for path in paths if not path.is_file()]
        if missing:
            raise FileNotFoundError(f"material file(s) not found: {', '.join(missing)}")
        log(f"using {len(paths)} provided local material(s)")
        return paths

    if args.stop_at not in {"materials", "video"}:
        return []
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    from scripts.generate_shorts_backgrounds import generate_backgrounds

    log(
        f"generating {args.background_count} local background clip(s) "
        f"in {args.backgrounds_dir}"
    )
    return generate_backgrounds(
        Path(args.backgrounds_dir),
        count=args.background_count,
        duration=args.background_duration,
        force=args.force_backgrounds,
        log=log,
    )


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))

    def log(message: str) -> None:
        print(message, file=sys.stderr, flush=True)

    if args.verify_upload_status:
        return verify_upload_status(Path(args.verify_upload_status))

    if args.cross_post_timeout <= 0:
        log("error: --cross-post-timeout must be greater than 0")
        return 2

    upload_platforms = [
        platform.strip().lower()
        for platform in (args.upload_platforms or "").split(",")
        if platform.strip()
    ]
    invalid_platforms = [
        platform for platform in upload_platforms if platform not in UPLOAD_PLATFORM_VALUES
    ]
    if not upload_platforms or invalid_platforms:
        log(
            "error: --upload-platforms must be a comma-separated list of "
            + ", ".join(UPLOAD_PLATFORM_VALUES)
        )
        return 2

    topic = (args.topic or os.getenv("SHORTS_TOPIC", "")).strip()
    script = (args.script or os.getenv("SHORTS_SCRIPT", "")).strip()
    gemini_api_key = os.getenv("GEMINI_API_KEY", "").strip()
    upload_api_key = os.getenv("UPLOAD_POST_API_KEY", "").strip()
    upload_username = os.getenv("UPLOAD_POST_USERNAME", "").strip()

    # Publishing is opt-in through the Upload-Post environment secrets. With
    # secrets present the pipeline publishes automatically; --no-upload
    # force-disables it; without secrets an already configured local
    # config.toml keeps working untouched.
    if args.no_upload:
        upload_enabled: bool | None = False
    elif upload_api_key and upload_username:
        upload_enabled = True
    else:
        upload_enabled = None

    upload_config_kwargs: dict = {}
    if upload_enabled is True:
        upload_config_kwargs = {
            "upload_api_key": upload_api_key,
            "upload_username": upload_username,
            "upload_platforms": upload_platforms,
            "upload_privacy": args.youtube_privacy,
            "upload_enabled": True,
        }
    elif upload_enabled is False:
        upload_config_kwargs = {"upload_enabled": False}

    try:
        changes = ensure_config(
            REPO_ROOT / "config.toml",
            REPO_ROOT / "config.example.toml",
            llm_provider=args.llm_provider,
            gemini_api_key=gemini_api_key,
            model_name=args.gemini_model,
            **upload_config_kwargs,
        )
    except (OSError, ValueError) as exc:
        log(f"error: could not prepare config.toml: {exc}")
        return 2
    for change in changes:
        log(f"config: {change}")

    upload_settings = read_upload_settings(REPO_ROOT / "config.toml")
    if upload_settings["configured"] and args.stop_at == "video":
        log(
            "publishing enabled: "
            + ", ".join(upload_settings["platforms"])
            + f" (privacy: {upload_settings['privacy']})"
        )
    elif args.stop_at == "video":
        reason = (
            "--no-upload given"
            if args.no_upload
            else " / ".join(UPLOAD_SECRET_ENV_VARS) + " not configured"
        )
        log(f"publishing disabled: {reason}")

    needs_llm = not script
    if needs_llm and not gemini_api_key:
        has_stored_key = False
        try:
            import toml

            stored = toml.load(str(REPO_ROOT / "config.toml"))
            has_stored_key = bool(stored.get("app", {}).get("gemini_api_key"))
        except Exception:
            has_stored_key = False
        if not has_stored_key:
            log(
                "error: GEMINI_API_KEY is not set and config.toml has no "
                "gemini_api_key; add the GitHub Actions secret GEMINI_API_KEY "
                "or pass --script to skip the LLM"
            )
            return 2

    try:
        if not topic:
            if script:
                topic = derive_subject(script)
                log(f"subject: {topic} (derived from --script)")
            else:
                log("requesting a topic from the configured LLM...")
                topic = pick_topic(build_topic_prompt())
                log(f"topic: {topic}")
        if not script:
            log("generating the narration script with the configured LLM...")
    except RuntimeError as exc:
        log(f"error: {exc}")
        return 1

    try:
        materials = resolve_materials(args, log)
    except (RuntimeError, ValueError, OSError, FileNotFoundError) as exc:
        log(f"error: {exc}")
        return 1

    if args.stop_at in {"materials", "video"} and not materials:
        log("error: no local materials are available for the materials stage")
        return 1

    command = build_cli_command(
        python=sys.executable,
        cli_path=REPO_ROOT / "cli.py",
        subject=topic,
        script=script,
        materials=materials,
        voice_name=args.voice_name,
        voice_rate=args.voice_rate,
        language=args.language,
        paragraph_number=args.paragraph_number,
        script_prompt="" if script else args.script_prompt,
        stop_at=args.stop_at,
        cross_post_timeout=args.cross_post_timeout,
        extra_args=args.cli_arg,
    )
    log("running: " + " ".join(_redact(command)))

    # The publish step runs inside cli.py after the video is final; its wait
    # time sits on top of generation, so widen the subprocess deadline only
    # when publishing is actually active.
    subprocess_timeout = args.task_timeout
    if upload_settings["configured"] and args.stop_at == "video":
        subprocess_timeout += int(args.cross_post_timeout) + 300

    try:
        result = run_cli_task(
            command,
            timeout=subprocess_timeout,
            require_video=args.stop_at == "video",
        )
    except (RuntimeError, subprocess.TimeoutExpired) as exc:
        log(f"error: {exc}")
        return 1

    script_text = script
    if not script_text:
        try:
            from app.utils import utils

            task_script = Path(utils.task_dir(result["task_id"])) / "script.json"
            payload = json.loads(task_script.read_text(encoding="utf-8"))
            script_text = str(payload.get("script") or "")
        except Exception:
            script_text = ""

    try:
        meta = collect_outputs(
            task_id=result["task_id"],
            videos=result["videos"],
            output_dir=Path(args.output_dir),
            subject=topic,
            script_text=script_text,
            voice_name=args.voice_name,
            extra_meta={
                "llm_provider": args.llm_provider,
                "aspect": "9:16",
                "language": args.language,
                "materials": [str(path) for path in materials],
            },
        )
    except OSError as exc:
        log(f"error: could not collect outputs: {exc}")
        return 1

    # The artifacts are already collected at this point: a failed publish is
    # reported below and never fails generation or removes the video.
    task_payload = result.get("result") if isinstance(result.get("result"), dict) else {}
    upload_report = build_upload_report(
        task_payload,
        task_id=result["task_id"],
        upload_settings=upload_settings,
        stop_at=args.stop_at,
    )
    try:
        status_path = write_upload_status(Path(args.output_dir), upload_report)
    except OSError as exc:
        log(f"error: could not write upload status: {exc}")
        return 1
    append_step_summary(upload_report)
    upload_detail = f" - {upload_report['reason']}" if upload_report.get("reason") else ""
    log(f"YouTube upload: {upload_report['status']}{upload_detail}")

    print(
        json.dumps(
            {
                "topic": topic,
                "task_id": result["task_id"],
                "outputs": meta["outputs"],
                "upload": upload_report,
                "upload_status_file": str(status_path),
            },
            ensure_ascii=False,
        )
    )
    return 0


def _redact(command: Sequence[str]) -> list[str]:
    """Keep the visible command line free of any configured secrets."""
    secret_markers = ("gemini_api_key", "upload_post_api_key", "upload_post_username")
    return [
        "<redacted>" if any(marker in token for marker in secret_markers) else token
        for token in command
    ]


if __name__ == "__main__":
    raise SystemExit(main())
