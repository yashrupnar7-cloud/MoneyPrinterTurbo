def ensure_config(
    config_path: Path,
    example_path: Path,
    *,
    llm_provider: str = "",
    gemini_api_key: str = "",
    model_name: str = "",
    upload_api_key: str = "",
    upload_username: str = "",
    upload_platforms: Sequence[str] = (),
    upload_privacy: str = "",
    upload_enabled: bool | None = None,
) -> list[str]:
    """Create/patch ``config.toml`` so the stock services do the right thing.

    LLM fields come from the Gemini environment variables; publishing fields
    come from the Upload-Post environment variables. Only these Modern Facts
    fields are touched: the rest of the configuration stays exactly as
    shipped. Secrets are never echoed into the returned change labels, and
    they are written only to ``config.toml`` (gitignored).

    ``upload_enabled=None`` leaves an existing Upload-Post configuration
    untouched (so a locally configured account still works without env vars);
    ``False`` force-disables publishing (``--no-upload``).
    """
    changes: list[str] = []
    if not config_path.is_file():
        if not example_path.is_file():
            raise FileNotFoundError(
                f"cannot create {config_path}: {example_path} is missing"
            )
        shutil.copyfile(example_path, config_path)
        changes.append(f"created {config_path.name} from {example_path.name}")

    import toml

    data = toml.load(str(config_path))
    app_section = data.setdefault("app", {})

    def apply(key: str, value: str, label: str) -> None:
        if value and app_section.get(key) != value:
            app_section[key] = value
            changes.append(label)

    def apply_value(key: str, value: object, label: str) -> None:
        if app_section.get(key) != value:
            app_section[key] = value
            changes.append(label)

    apply("llm_provider", llm_provider, f"app.llm_provider = {llm_provider}")
    apply("gemini_api_key", gemini_api_key, "app.gemini_api_key set from GEMINI_API_KEY")
    apply("gemini_model_name", model_name, f"app.gemini_model_name = {model_name}")

    if upload_enabled is True:
        apply(
            "upload_post_api_key",
            upload_api_key,
            "app.upload_post_api_key set from UPLOAD_POST_API_KEY",
        )
        apply(
            "upload_post_username",
            upload_username,
            "app.upload_post_username set from UPLOAD_POST_USERNAME",
        )
        platforms = [str(platform) for platform in upload_platforms]
        if platforms:
            apply_value(
                "upload_post_platforms",
                platforms,
                "app.upload_post_platforms = " + ", ".join(platforms),
            )
        if upload_privacy:
            apply_value(
                "upload_post_youtube_privacy_status",
                upload_privacy,
                f"app.upload_post_youtube_privacy_status = {upload_privacy}",
            )
        apply_value(
            "upload_post_enabled", True, "app.upload_post_enabled = true"
        )
        apply_value(
            "upload_post_auto_upload", True, "app.upload_post_auto_upload = true"
        )
    elif upload_enabled is False:
        apply_value(
            "upload_post_enabled", False, "app.upload_post_enabled = false"
        )
        apply_value(
            "upload_post_auto_upload", False, "app.upload_post_auto_upload = false"
        )

    if changes:
        config_path.write_text(toml.dumps(data), encoding="utf-8")
    return changes


def read_upload_settings(config_path: Path) -> dict:
    """Mirror the pipeline's own publishing gate for reporting decisions.

    ``task.py`` only schedules a cross-post when ``is_configured()`` (enabled
    + API key + username) AND ``auto_upload`` are both true and platforms are
    non-empty; this reads the same ``config.toml`` fields so the report says
    "disabled" exactly when the pipeline skipped publishing.
    """
    app_section: dict = {}
    try:
        import toml

        app_section = toml.load(str(config_path)).get("app", {})
    except Exception:
        app_section = {}
    platforms = app_section.get("upload_post_platforms", ["tiktok", "instagram"])
    if not isinstance(platforms, list):
        platforms = []
    configured = bool(
        app_section.get("upload_post_enabled")
        and app_section.get("upload_post_auto_upload")
        and app_section.get("upload_post_api_key")
        and app_section.get("upload_post_username")
        and platforms
    )
    return {
        "configured": configured,
        "platforms": [str(platform) for platform in platforms],
        "privacy": str(
            app_section.get("upload_post_youtube_privacy_status")
            or "public"
        ),
    }


def build_upload_report(
    task_result: dict,
    *,
    task_id: str,
    upload_settings: dict,
    stop_at: str = "video",
) -> dict:
    """Turn the CLI cross-post outcome into a stable upload-status payload.

    The report never contains credentials; it is written next to the video
    and consumed by ``--verify-upload-status``.
    """
    state = task_result.get("cross_post_state")
    if stop_at != "video":
        status = "skipped"
        reason = f"video pipeline stopped at '{stop_at}'"
    elif not upload_settings.get("configured"):
        status = "disabled"
        reason = (
            "Upload-Post publishing is not configured; set "
            + " and ".join(UPLOAD_SECRET_ENV_VARS)
            + " (see docs/modern-facts-shorts.md)"
        )
    elif state == "complete":
        status = "uploaded"
        reason = None
    elif state == "failed":
        status = "failed"
        reason = str(
            task_result.get("cross_post_error") or "unknown upload error"
        )
    elif state in ("pending", "processing"):
        status = "failed"
        reason = (
            "cross-post upload did not finish before the CLI exited; "
            "outcome unconfirmed"
        )
    else:
        status = "failed"
        reason = "cross-post was not scheduled despite being configured"
    return {
        "status": status,
        "reason": reason,
        "cross_post_state": state,
        "task_id": task_id,
        "platforms": list(upload_settings.get("platforms") or []),
        "youtube_privacy_status": upload_settings.get("privacy", "public"),
        "results": task_result.get("cross_post_results") or [],
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


def write_upload_status(output_dir: Path, report: dict) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / UPLOAD_STATUS_FILENAME
    path.write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return path


def append_step_summary(report: dict) -> None:
    """Append a credential-free publish summary when running in GitHub Actions."""
    target = os.getenv("GITHUB_STEP_SUMMARY")
    if not target:
        return

    def one_line(value: object) -> str:
        return re.sub(r"\s+", " ", str(value)).strip()

    lines = [
        "## YouTube upload",
        "",
        f"- status: `{one_line(report.get('status'))}`",
        f"- privacy: `{one_line(report.get('youtube_privacy_status'))}`",
        "- platforms: `"
        + one_line(", ".join(report.get("platforms") or []))
        + "`",
    ]
    if report.get("reason"):
        lines.append(f"- detail: {one_line(report['reason'])}")
    try:
        with open(target, "a", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
    except OSError:
        pass


def verify_upload_status(status_path: Path) -> int:
    """Exit non-zero only when a configured publish actually failed.

    A missing file means generation never succeeded (the job already failed
    earlier), and ``disabled``/``skipped`` mean publishing was never
    requested — neither is an upload error.
    """
    if not status_path.is_file():
        print(
            f"no upload status file at {status_path}; video generation did "
            "not complete, skipping the YouTube upload check"
        )
        return 0
    try:
        data = json.loads(status_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"could not read upload status {status_path}: {exc}", file=sys.stderr)
        return 1
    status = str(data.get("status") or "failed")
    reason = str(data.get("reason") or "")
    if status in {"uploaded", "disabled", "skipped"}:
        detail = f" - {reason}" if reason else ""
        print(f"YouTube upload status: {status}{detail}")
        return 0
    message = f"YouTube upload failed: {reason or 'unknown error'}"
    print(message, file=sys.stderr)
    if os.getenv("GITHUB_ACTIONS") == "true":
        print(f"::error::{message}")
    return 1


def build_topic_prompt(channel: str = "Modern Facts") -> str:
    return TOPIC_PROMPT.replace("Modern Facts", channel)


def parse_topic_response(raw: object) -> str:
    """Reduce an LLM reply to a single usable topic line ('' when unusable)."""
    if not isinstance(raw, str):
        return ""
    text = raw.strip()
    if not text or text.startswith("Error:"):
        return ""
    if text.startswith("```"):
        text = re.sub(r"^```[a-zA-Z0-9]*\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    for line in text.splitlines():
        candidate = line.strip().lstrip("#").lstrip("-*").strip()
        candidate = re.sub(r'^(topic|title)\s*:\s*', "", candidate, flags=re.I)
        candidate = candidate.strip(" \t\"'\u201c\u201d")
        if candidate:
            return candidate[:160]
    return ""


def pick_topic(
    prompt: str,
    *,
    generate: Callable[..., str] | None = None,
    attempts: int = 3,
) -> str:
    """Ask the configured LLM for one topic, retrying transient failures."""
    if generate is None:
        if str(REPO_ROOT) not in sys.path:
            sys.path.insert(0, str(REPO_ROOT))
        from app.services import llm as llm_service

        generate = llm_service._generate_response

    last_reply: object = None
    for _ in range(attempts):
        last_reply = generate(prompt=prompt)
        topic = parse_topic_response(last_reply)
        if topic:
            return topic
    raise RuntimeError(
        "failed to generate a topic with the configured LLM; "
        f"last reply: {str(last_reply)[:300]}"
    )


def build_cli_command(
    *,
    python: str,
    cli_path: Path,
    subject: str = "",
    script: str = "",
    materials: Sequence[Path] = (),
    voice_name: str = DEFAULT_VOICE_NAME,
    voice_rate: float = DEFAULT_VOICE_RATE,
    language: str = DEFAULT_LANGUAGE,
    paragraph_number: int = 2,
    script_prompt: str = "",
    aspect: str = "9:16",
    stop_at: str = "video",
    video_count: int = 1,
    cross_post_timeout: float | None = None,
    extra_args: Sequence[str] = (),
) -> list[str]:
    """Build the argument vector for the existing ``cli.py`` entry point."""
    command = [python, str(cli_path)]
    if subject:
        command.extend(["--video-subject", subject])
    if script:
        command.extend(["--video-script", script])
    command.extend(
        [
            "--video-source",
            "local",
            "--video-materials",
            ",".join(str(path) for path in materials),
            "--video-aspect",
            aspect,
            "--video-language",
            language,
            "--paragraph-number",
            str(paragraph_number),
            "--voice-name",
            voice_name,
            "--voice-rate",
            f"{voice_rate:g}",
            "--subtitle-enabled",
            "--video-count",
            str(video_count),
            "--stop-at",
            stop_at,
        ]
    )
    if script_prompt:
        command.extend(["--video-script-prompt", script_prompt])
    if cross_post_timeout is not None:
        command.extend(["--cross-post-timeout", f"{cross_post_timeout:g}"])
    command.extend(extra_args)
    return command


def run_cli_task(
    command: Sequence[str],
    *,
    timeout: int = DEFAULT_TASK_TIMEOUT,
    require_video: bool = True,
) -> dict:
    """Run ``cli.py`` and return its single-line JSON result."""
    completed = subprocess.run(
        list(command),
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
        check=False,
    )
    stdout = completed.stdout or ""
    result = None
    for line in reversed(stdout.splitlines()):
        stripped = line.strip()
        if stripped.startswith("{"):
            try:
                result = json.loads(stripped)
                break
            except json.JSONDecodeError:
                continue
    if completed.returncode != 0 or result is None:
        stderr_tail = "\n".join((completed.stderr or "").splitlines()[-40:])
        raise RuntimeError(
            "cli.py failed with exit code "
            f"{completed.returncode}; last log lines:\n{stderr_tail}"
        )
    payload = result.get("result") if isinstance(result.get("result"), dict) else {}
    if not payload or payload.get("state") not in (None, "completed"):
        error = (payload or {}).get("error") or "unknown task error"
        raise RuntimeError(f"video task did not complete: {error}")
    task_id = str(result.get("task_id") or "")
    videos = [str(path) for path in (payload.get("videos") or [])]
    if not task_id:
        raise RuntimeError("cli.py finished without a task id")
    if require_video and not videos:
        raise RuntimeError("cli.py finished without an output video")
    result["task_id"] = task_id
    result["videos"] = videos
    return result


def derive_subject(script: str, limit: int = 100) -> str:
    """Use the script's opening sentence as the video subject/topic."""
    first = re.split(r"[.!?\n]", script.strip(), maxsplit=1)[0].strip()
    first = re.sub(r"\s+", " ", first)
    return first[:limit].strip() or "Modern Facts short"


def slugify(text: str, max_length: int = 40) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:max_length].rstrip("-") or "short"


def collect_outputs(
    *,
    task_id: str,
    videos: Sequence[str],
    output_dir: Path,
    subject: str,
    script_text: str,
    voice_name: str,
    extra_meta: dict | None = None,
) -> dict:
    """Copy the finished artifacts into ``output_dir`` and write metadata."""
    if str(REPO_ROOT) not in sys.path:
        sys.path.insert(0, str(REPO_ROOT))
    from app.utils import utils

    task_dir = Path(utils.task_dir(task_id))
    output_dir.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    slug = slugify(subject)

    copied_videos = []
    for index, source in enumerate(videos, start=1):
        source_path = Path(source)
        if not source_path.is_file():
            continue
        suffix = "" if len(videos) == 1 else f"-{index}"
        target = output_dir / f"modern-facts-{stamp}-{slug}{suffix}.mp4"
        shutil.copy2(source_path, target)
        copied_videos.append(str(target))

    copied: dict[str, list[str]] = {"videos": copied_videos}
    for name in ("subtitle.srt", "script.json"):
        source_path = task_dir / name
        if source_path.is_file():
            target = output_dir / f"{stamp}-{slug}-{name}"
            shutil.copy2(source_path, target)
            copied.setdefault(name, []).append(str(target))

    meta = {
        "subject": subject,
        "script": script_text,
        "voice_name": voice_name,
        "task_id": task_id,
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "outputs": copied,
    }
    if extra_meta:
        meta.update(extra_meta)
    meta_path = output_dir / f"{stamp}-{slug}-meta.json"
    meta_path.write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    copied["meta"] = [str(meta_path)]
    return meta


